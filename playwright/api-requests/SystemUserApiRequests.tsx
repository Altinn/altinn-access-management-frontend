import { TestdataApi } from 'playwright/util/TestdataApi';

import { asEnterprise, asUser, token } from './callAs';
import { ApiError, platformUrl } from './apiRequest';

const AUTHENTICATION = 'authentication/api/v1';

const SCOPES = {
  registerWrite: 'altinn:authentication/systemregister.write',
  requestWrite: 'altinn:authentication/systemuser.request.write',
  request:
    'altinn:authentication/systemuser.request.read altinn:authentication/systemuser.request.write',
  registerDelete:
    'altinn:authentication/systemuser.request.write altinn:authentication/systemregister.write altinn:authentication/systemuser.request.read',
};

type Rights = { resource: { value: string; id: string }[] }[];
type AccessPackages = { urn: string }[];
type CreatedRequest = { confirmUrl: string; id: string };

/** System register and system user setup: systems are created by the vendor, users by the party. */
export class ApiRequests {
  public async createSystemInSystemregisterWithAccessPackages(
    vendorOrgNo: string,
    name: string,
    accessPackages?: AccessPackages,
    redirectUrl?: string,
    rights?: Rights,
  ): Promise<string> {
    await this.registerSystem(vendorOrgNo, name, {
      Description: {
        en: 'This is auto generated by an integration test. Some data is randomized, but some is not - like this description',
        nb: 'Integrasjonstest. Noe er randomisert her, men mye blir likt.',
        nn: 'integrasjonstest på nynorsk. Noe er randomisert her, men mye blir likt.',
      },
      rights: rights ?? [],
      accessPackages: accessPackages ?? [
        { urn: 'urn:altinn:accesspackage:regnskapsforer-med-signeringsrettighet' },
        { urn: 'urn:altinn:accesspackage:regnskapsforer-uten-signeringsrettighet' },
        { urn: 'urn:altinn:accesspackage:regnskapsforer-lonn' },
        { urn: 'urn:altinn:accesspackage:ansvarlig-revisor' },
        { urn: 'urn:altinn:accesspackage:revisormedarbeider' },
        { urn: 'urn:altinn:accesspackage:skattegrunnlag' },
        { urn: 'urn:altinn:accesspackage:forretningsforer-eiendom' },
      ],
      allowedRedirectUrls: [redirectUrl ?? 'https://www.vg.no'],
      isVisible: false,
    });
    return `${vendorOrgNo}_${name}`;
  }

  public async createSystemSystemRegister(vendorOrgNo: string): Promise<string> {
    // Max 10 chars: E2E + last 5 digits of timestamp + 2 random digits
    const randomDigits = Math.floor(Math.random() * 100)
      .toString()
      .padStart(2, '0');
    const name = `E2E${Date.now().toString().slice(-5)}${randomDigits}`;

    await this.registerSystem(vendorOrgNo, name, {
      Description: {
        en: 'Authentication-e2e-Playwright-English-description',
        nb: 'Authentication-e2e-Playwright-bokmaal-beskrivelse',
        nn: 'Authentication-e2e-Playwright-nynorsk-beskriving',
      },
      rights: [
        { resource: [{ value: 'authentication-e2e-test', id: 'urn:altinn:resource' }] },
        { resource: [{ value: 'vegardtestressurs', id: 'urn:altinn:resource' }] },
      ],
      allowedRedirectUrls: ['https://altinn.no'],
      isVisible: true,
    });
    return name;
  }

  public async deleteSystemInSystemRegister(vendorOrgNo: string, systemName: string) {
    await asEnterprise(
      vendorOrgNo,
      SCOPES.registerDelete,
      'DELETE',
      platformUrl(`${AUTHENTICATION}/systemregister/vendor/${vendorOrgNo}_${systemName}`),
    );
  }

  public async postSystemuserRequest(
    vendorOrgNo: string,
    externalRef: string,
    systemId: string,
    partyOrgNo: string,
    redirectUrl?: string,
    rights?: Rights,
    accessPackages?: AccessPackages,
  ) {
    return asEnterprise<CreatedRequest>(
      vendorOrgNo,
      SCOPES.request,
      'POST',
      platformUrl(`${AUTHENTICATION}/systemuser/request/vendor`),
      {
        systemId,
        partyOrgNo,
        externalRef,
        rights: rights ?? [],
        accessPackages: accessPackages ?? [{ urn: 'urn:altinn:accesspackage:baerekraft' }],
        redirectUrl: redirectUrl ?? '',
      },
    );
  }

  public async postClientDelegationAgentRequest(
    vendorOrgNo: string,
    systemId: string,
    accessPackageUrn: string,
    partyOrgNo: string,
    externalRef: string = TestdataApi.generateExternalRef(),
  ) {
    return asEnterprise<CreatedRequest>(
      vendorOrgNo,
      SCOPES.request,
      'POST',
      platformUrl(`${AUTHENTICATION}/systemuser/request/vendor/agent`),
      {
        externalRef,
        systemId,
        partyOrgNo,
        accessPackages: [{ urn: `urn:altinn:accesspackage:${accessPackageUrn}` }],
        redirectUrl: '',
      },
    );
  }

  public async postSystemuserChangeRequest(
    vendorOrgNo: string,
    systemUserId: string,
    changes: {
      requiredRights: Rights;
      unwantedRights: Rights;
      requiredAccessPackages: AccessPackages;
      unwantedAccessPackages: AccessPackages;
    },
  ) {
    return asEnterprise<CreatedRequest>(
      vendorOrgNo,
      SCOPES.request,
      'POST',
      platformUrl(`${AUTHENTICATION}/systemuser/changerequest/vendor`, {
        'correlation-id': crypto.randomUUID(),
        'system-user-id': systemUserId,
      }),
      changes,
    );
  }

  public async getStatusForSystemUserRequest<T>(
    vendorOrgNo: string,
    systemRequestId: string,
  ): Promise<T> {
    return asEnterprise<T>(
      vendorOrgNo,
      SCOPES.request,
      'GET',
      platformUrl(`${AUTHENTICATION}/systemuser/request/vendor/${systemRequestId}`),
    );
  }

  public async getStatusForSystemUserChangeRequest<T>(
    vendorOrgNo: string,
    systemRequestId: string,
  ): Promise<T> {
    return asEnterprise<T>(
      vendorOrgNo,
      SCOPES.request,
      'GET',
      platformUrl(`${AUTHENTICATION}/systemuser/changerequest/vendor/${systemRequestId}`),
    );
  }

  public async getSystemUserByQuery(
    vendorOrgNo: string,
    systemId: string,
    orgno: string,
    externalRef: string,
  ): Promise<string> {
    const systemUser = await asEnterprise<{ id: string }>(
      vendorOrgNo,
      SCOPES.requestWrite,
      'GET',
      platformUrl(`${AUTHENTICATION}/systemuser/vendor/byquery`, {
        'system-id': systemId,
        orgno,
        'external-ref': externalRef,
      }),
    );
    return systemUser.id;
  }

  public async approveSystemuserRequest(requestId: string, partyOrgNo: string, userPid: string) {
    const { partyId } = await token.getIds(partyOrgNo);
    await asUser(
      userPid,
      'POST',
      platformUrl(`${AUTHENTICATION}/systemuser/request/${partyId}/${requestId}/approve`),
    );
  }

  /** Clean up this test's users, including after failed setup or UI verification. */
  public async cleanUpSystemUsersForSystem(
    systemId: string,
    userPid: string,
    partyOrgNo: string,
    agent = false,
    externalRef?: string,
  ): Promise<void> {
    const { partyId, partyUuid } = await token.getIds(partyOrgNo);
    const path = `${AUTHENTICATION}/systemuser/${agent ? 'agent/' : ''}${partyId}`;
    const users = await asUser<{ id: string; systemId: string; externalRef: string }[]>(
      userPid,
      'GET',
      platformUrl(path),
    );

    for (const user of users.filter(
      (user) =>
        user.systemId === systemId &&
        (externalRef === undefined || user.externalRef === externalRef),
    )) {
      // A 404 means the system user is already gone, which is what cleanup wants.
      await asUser(
        userPid,
        'DELETE',
        platformUrl(`${path}/${user.id}`, { partyuuid: agent ? partyUuid : undefined }),
      ).catch((error) => {
        if (!(error instanceof ApiError && error.status === 404)) throw error;
      });
    }
  }

  public async cleanUpSystemUsers(
    systemUsers: { id: string }[],
    userPid: string,
    partyOrgNo: string,
  ): Promise<void> {
    for (const systemUser of systemUsers) {
      await this.deleteRegularSystemUser(systemUser.id, partyOrgNo, userPid);
    }
  }

  public async deleteRegularSystemUser(
    systemUserId: string,
    partyOrgNo: string,
    userPid: string,
  ): Promise<void> {
    const { partyId } = await token.getIds(partyOrgNo);
    await asUser(
      userPid,
      'DELETE',
      platformUrl(`${AUTHENTICATION}/systemuser/${partyId}/${systemUserId}`),
    );
  }

  public async deleteAgentSystemUser(
    vendorOrgNo: string,
    systemId: string,
    partyOrgNo: string,
    externalRef: string,
    userPid: string,
  ): Promise<void> {
    const { partyId, partyUuid } = await token.getIds(partyOrgNo);
    const systemUserId = await this.getSystemUserByQuery(
      vendorOrgNo,
      systemId,
      partyOrgNo,
      externalRef,
    );
    await asUser(
      userPid,
      'DELETE',
      platformUrl(`${AUTHENTICATION}/systemuser/agent/${partyId}/${systemUserId}`, {
        partyuuid: partyUuid,
      }),
    );
  }

  /** Registers a system owned by the vendor; the fields that differ per test are in `details`. */
  private async registerSystem(vendorOrgNo: string, name: string, details: object) {
    await asEnterprise(
      vendorOrgNo,
      SCOPES.registerWrite,
      'POST',
      platformUrl(`${AUTHENTICATION}/systemregister/vendor`),
      {
        Id: `${vendorOrgNo}_${name}`,
        Vendor: { ID: `0192:${vendorOrgNo}` },
        Name: { en: name, nb: name, nn: name },
        ClientId: [`Client_${Date.now()}_${Math.random()}`],
        ...details,
      },
    );
  }
}
